let current = 'ar';

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'ar';
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
}

export const getLang = () => current;

/** Translate a key with optional {placeholders}. */
export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.ar[key] ?? key;
  if (vars && typeof s === 'string') {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  }
  return s;
}

/** Pick the current-language value from a {ar, fr} object. */
export const L = (obj) => (obj ? obj[current] ?? obj.ar : '');

/** Locale-aware number formatting (Western digits in both languages for clarity). */
export function num(n, digits = 0) {
  if (n == null || Number.isNaN(n)) return '—';
  return new Intl.NumberFormat(current === 'ar' ? 'ar-DZ-u-nu-latn' : 'fr-FR', {
    maximumFractionDigits: digits,
    minimumFractionDigits: 0,
    useGrouping: false, // avoid '2.250' (ar-DZ) being read as a decimal
  }).format(n);
}

export function fmtDate(iso, opts = { day: 'numeric', month: 'short' }) {
  if (!iso) return '';
  const [y, m, d] = iso.split('-').map(Number);
  return new Intl.DateTimeFormat(current === 'ar' ? 'ar-DZ-u-nu-latn' : 'fr-FR', opts).format(new Date(y, m - 1, d));
}
